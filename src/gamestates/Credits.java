package gamestates;

import java.awt.BasicStroke;
import java.awt.Color;
import java.awt.Graphics;
import java.awt.Graphics2D;
import java.awt.RenderingHints;
import java.awt.Stroke;
import java.awt.event.KeyEvent;
import java.awt.event.MouseEvent;
import java.awt.image.BufferedImage;
import java.util.ArrayList;

import main.Game;
import utilz.LoadSave;

public class Credits extends State implements Statemethods {
	private BufferedImage backgroundImg, creditsImg;
	private int bgX, bgY, bgW, bgH;
	private float bgYFloat;

	private ArrayList<ShowEntity> entitiesList;

	// ── High-res member photos drawn over the scrolling PNG ──────────────────
	private BufferedImage[] memberPhotos;

	// Coordinates in original PNG-space (pre-scale) matching the cards baked
	// into credits_list.png (generated by generate_credits.py).
	// PHOTO_SIZE_ORIG = 96 px,  PHOTO_X_ORIG = 18 px (PADDING(12)+6)
	private static final int   PHOTO_SIZE_ORIG = 96;
	private static final int   PHOTO_X_ORIG    = 18;
	// photo_y = card_y + (CARD_H - PHOTO_SIZE) / 2 = card_y + (170-96)/2 = card_y + 37
	private static final int[] PHOTO_Y_ORIG = { 107, 287, 467 };

	// Card border colors
	private static final Color LEAD_BORDER = new Color(180, 130, 30);
	private static final Color CARD_BORDER = new Color(80,  55,  20);

	public Credits(Game game) {
		super(game);
		backgroundImg = LoadSave.GetSpriteAtlas(LoadSave.MENU_BACKGROUND_IMG);
		creditsImg    = LoadSave.GetSpriteAtlas(LoadSave.CREDITS);
		bgW = (int) (creditsImg.getWidth()  * Game.SCALE);
		bgH = (int) (creditsImg.getHeight() * Game.SCALE);
		bgX = Game.GAME_WIDTH / 2 - bgW / 2;
		bgY = Game.GAME_HEIGHT;
		loadEntities();
		loadMemberPhotos();
	}

	private void loadEntities() {
		entitiesList = new ArrayList<>();
		entitiesList.add(new ShowEntity(getIdleAni(LoadSave.GetSpriteAtlas(LoadSave.PLAYER_ATLAS),   5, 64, 40), (int) (Game.GAME_WIDTH * 0.05), (int) (Game.GAME_HEIGHT * 0.8)));
		entitiesList.add(new ShowEntity(getIdleAni(LoadSave.GetSpriteAtlas(LoadSave.CRABBY_SPRITE),  9, 72, 32), (int) (Game.GAME_WIDTH * 0.15), (int) (Game.GAME_HEIGHT * 0.75)));
		entitiesList.add(new ShowEntity(getIdleAni(LoadSave.GetSpriteAtlas(LoadSave.PINKSTAR_ATLAS), 8, 34, 30), (int) (Game.GAME_WIDTH * 0.7),  (int) (Game.GAME_HEIGHT * 0.75)));
		entitiesList.add(new ShowEntity(getIdleAni(LoadSave.GetSpriteAtlas(LoadSave.SHARK_ATLAS),    8, 34, 30), (int) (Game.GAME_WIDTH * 0.8),  (int) (Game.GAME_HEIGHT * 0.8)));
	}

	/** Load and pre-crop each member's photo to a square at display resolution. */
	private void loadMemberPhotos() {
		String[] files = {
			LoadSave.MEMBER_PHOTO_RADOAN,
			LoadSave.MEMBER_PHOTO_ABRAR,
			LoadSave.MEMBER_PHOTO_TASNIM
		};
		int displaySize = (int) (PHOTO_SIZE_ORIG * Game.SCALE); // 192 px on-screen
		memberPhotos = new BufferedImage[files.length];
		for (int i = 0; i < files.length; i++) {
			BufferedImage raw = LoadSave.GetSpriteAtlas(files[i]);
			if (raw != null)
				memberPhotos[i] = cropAndScale(raw, displaySize);
		}
	}

	/** Center-crop to square (biased upward to capture the face) then scale. */
	private BufferedImage cropAndScale(BufferedImage src, int target) {
		int pw = src.getWidth(), ph = src.getHeight();
		int side, cx, cy;
		if (pw <= ph) {
			side = pw;
			cx   = 0;
			cy   = Math.max(0, Math.min((ph - pw) / 6, ph - pw));
		} else {
			side = ph;
			cx   = (pw - ph) / 2;
			cy   = 0;
		}
		BufferedImage cropped = src.getSubimage(cx, cy, side, side);
		BufferedImage result  = new BufferedImage(target, target, BufferedImage.TYPE_INT_RGB);
		Graphics2D g2 = result.createGraphics();
		g2.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
		g2.setRenderingHint(RenderingHints.KEY_RENDERING,     RenderingHints.VALUE_RENDER_QUALITY);
		g2.drawImage(cropped, 0, 0, target, target, null);
		g2.dispose();
		return result;
	}

	private BufferedImage[] getIdleAni(BufferedImage atlas, int count, int w, int h) {
		BufferedImage[] arr = new BufferedImage[count];
		for (int i = 0; i < count; i++)
			arr[i] = atlas.getSubimage(w * i, 0, w, h);
		return arr;
	}

	@Override
	public void update() {
		bgYFloat -= 0.2f;
		for (ShowEntity se : entitiesList)
			se.update();
	}

	@Override
	public void draw(Graphics g) {
		g.drawImage(backgroundImg, 0, 0, Game.GAME_WIDTH, Game.GAME_HEIGHT, null);
		g.drawImage(creditsImg, bgX, (int) (bgY + bgYFloat), bgW, bgH, null);
		drawMemberPhotos(g);
		for (ShowEntity se : entitiesList)
			se.draw(g);
	}

	/**
	 * Overlay the high-res member photos at the exact card positions defined
	 * in the scrolling credits PNG, covering the low-res thumbnails baked in.
	 */
	private void drawMemberPhotos(Graphics g) {
		if (memberPhotos == null) return;
		int displaySize  = (int) (PHOTO_SIZE_ORIG * Game.SCALE);
		int screenPhotoX = bgX + (int) (PHOTO_X_ORIG * Game.SCALE);
		int borderPx     = 3;

		Graphics2D g2 = (Graphics2D) g;

		for (int i = 0; i < memberPhotos.length; i++) {
			if (memberPhotos[i] == null) continue;

			int screenPhotoY = (int) (bgY + bgYFloat + PHOTO_Y_ORIG[i] * Game.SCALE);

			// Skip if entirely off-screen
			if (screenPhotoY > Game.GAME_HEIGHT || screenPhotoY + displaySize < 0) continue;

			// Border ring
			Color bc = (i == 0) ? LEAD_BORDER : CARD_BORDER;
			Stroke old = g2.getStroke();
			g2.setStroke(new BasicStroke(borderPx));
			g2.setColor(bc);
			g2.drawRect(screenPhotoX - borderPx,
						screenPhotoY - borderPx,
						displaySize + borderPx * 2 - 1,
						displaySize + borderPx * 2 - 1);
			g2.setStroke(old);

			// High-res photo
			g.drawImage(memberPhotos[i], screenPhotoX, screenPhotoY, displaySize, displaySize, null);
		}
	}

	@Override
	public void keyReleased(KeyEvent e) {
		if (e.getKeyCode() == KeyEvent.VK_ESCAPE) {
			bgYFloat = 0;
			setGamestate(Gamestate.MENU);
		}
	}

	@Override public void mouseMoved(MouseEvent e)   {}
	@Override public void mousePressed(MouseEvent e)  {}
	@Override public void mouseReleased(MouseEvent e) {}
	@Override public void mouseClicked(MouseEvent e)  {}
	@Override public void keyPressed(KeyEvent e)      {}

	private class ShowEntity {
		private BufferedImage[] idleAnimation;
		private int x, y, aniIndex, aniTick;

		public ShowEntity(BufferedImage[] idleAnimation, int x, int y) {
			this.idleAnimation = idleAnimation;
			this.x = x;
			this.y = y;
		}

		public void draw(Graphics g) {
			g.drawImage(idleAnimation[aniIndex], x, y,
					(int) (idleAnimation[aniIndex].getWidth()  * 4),
					(int) (idleAnimation[aniIndex].getHeight() * 4), null);
		}

		public void update() {
			if (++aniTick >= 25) {
				aniTick = 0;
				if (++aniIndex >= idleAnimation.length)
					aniIndex = 0;
			}
		}
	}
}
